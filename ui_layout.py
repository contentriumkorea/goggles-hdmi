def build_view_menu(w):
    menu = QMenu(w)
    for control in (w.zebra_control, w.crop_control):
        action = menu.addAction(control.text())
        action.setCheckable(True)
        action.toggled.connect(control.setChecked)
        control.toggled.connect(action.setChecked)
    menu.addSeparator()
    group = QActionGroup(menu)
    group.setExclusive(True)
    for index in range(w.preview_mode.count()):
        action = menu.addAction(w.preview_mode.itemText(index))
        action.setCheckable(True)
        action.setChecked(index == 0)
        action.triggered.connect(lambda _, i=index: w.preview_mode.setCurrentIndex(i))
        group.addAction(action)
    w.preview_mode.currentIndexChanged.connect(lambda i: group.actions()[i].setChecked(True))
    w.view_options.setMenu(menu)
