class ReviewMode(QComboBox):
    toggled = Signal(bool)

    def __init__(self):
        super().__init__()
        self.addItems(['즉시 반영', '검토 후 적용'])
        self.currentIndexChanged.connect(lambda index: self.toggled.emit(index == 1))
        self.setAccessibleName('보정 반영 방식')
        self.setToolTip('검토 모드에서는 적용을 눌러야 HDMI에 반영됩니다.\n즉시 반영으로 전환하면 미적용 변경을 취소합니다.')

    def setChecked(self, checked):
        self.setCurrentIndex(1 if checked else 0)

    def isChecked(self):
        return self.currentIndex() == 1


def button(title, callback, box=None):
    control = QPushButton(title)
    control.clicked.connect(callback)
    if box is not None:
        box.addWidget(control)
    return control


